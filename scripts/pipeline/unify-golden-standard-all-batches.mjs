// 3. 通貨・売上・利益率のフォーマット
// ----------------------------------------------------
function formatMoneyStats(e) {
  const pnl = e.pnl || {};
  let rev = pnl.revenueLabel || "";
  if (!rev || rev === "高粗利ストック") {
    if (pnl.revenueJPY && pnl.revenueJPY > 0) {
      if (pnl.revenueJPY >= 100_000_000) {
        rev = "年商¥" + (pnl.revenueJPY / 100_000_000).toFixed(1).replace(/\.0$/, "") + "億円";
      } else if (pnl.revenueJPY >= 10_000) {
        rev = "月商¥" + Math.round(pnl.revenueJPY / 10_000 / (pnl.periodType === "ANNUAL" ? 12 : 1)).toLocaleString() + "万円";
      }
    } else {
      rev = "月商数百万円";
    }
  }

  const opMargin = pnl.operatingMargin && pnl.operatingMargin > 0 ? Math.round(pnl.operatingMargin) : 70;
  const grossMargin = pnl.grossMargin && pnl.grossMargin > 0 ? Math.round(pnl.grossMargin) : 85;

  return { rev, opMargin, grossMargin };
}

