// 5. タグの完全日本語化と統一生成
// ----------------------------------------------------
function buildJapaneseTags(e, dna, money) {
  const newTags = new Set();

  for (const t of (e.tags || [])) {
    if (TAG_TRANSLATION_MAP[t]) {
      newTags.add(TAG_TRANSLATION_MAP[t]);
    } else if (/^[\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FAF]/.test(t) && !t.includes("_")) {
      newTags.add(t);
    }
  }

  const team = e.operations?.teamSize || (e.tags?.includes("founders-solo") ? 1 : 2);
  if (team === 1 || e.tags?.includes("完全1人開発") || e.tags?.includes("完全ソロ運営")) {
    newTags.add("持たざる個人の成り上がり");
    newTags.add("完全1人開発");
  } else if (team <= 5) {
    newTags.add("少数精鋭");
    newTags.add("極小チーム(2-5名)");
  } else {
    newTags.add("少数精鋭");
  }

  if (money.opMargin >= 75) {
    newTags.add("利益率80%超");
    newTags.add("超高粗利");
  } else if (money.opMargin >= 60) {
    newTags.add("高利益率");
  }
  newTags.add("損益分岐点ゼロ");

  newTags.add("完全勝ち組");
  newTags.add("再現性重視");
  if (dna.domainTag && !dna.domainTag.includes("_") && !/^[a-zA-Z0-9_-]+$/.test(dna.domainTag)) {
    newTags.add(dna.domainTag);
  }

  if (money.rev.includes("月商")) {
    const m = money.rev.match(/月商¥?([0-9,]+万円)/);
    if (m) newTags.add("月商" + m[1]);
  } else if (money.rev.includes("年商")) {
    const m = money.rev.match(/年商¥?([0-9.]+億円)/);
    if (m) newTags.add("年商" + m[1]);
  }

  const sanitized = Array.from(newTags).filter(t => !/^[a-zA-Z0-9_-]+$/.test(t));
  return sanitized.slice(0, 8);
}

